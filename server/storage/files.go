package storage

import (
	"context"
	"database/sql"
)

// File is an uploaded file that dynamic codes can serve instead of redirecting.
type File struct {
	ID          string
	UserID      string
	Name        string
	ContentType string
	Size        int64
	SHA256      string
	StorageKey  string // file name inside the upload directory, generated by the server
	CreatedAt   int64

	// Derived: number of codes currently serving this file.
	CodeCount int64
}

const fileSelect = `SELECT f.id, f.user_id, f.name, f.content_type, f.size, f.sha256, f.storage_key, f.created_at,
	(SELECT COUNT(*) FROM qrcodes q WHERE q.file_id = f.id) AS code_count
	FROM files f`

func scanFile(row interface{ Scan(...any) error }) (*File, error) {
	var f File
	err := row.Scan(&f.ID, &f.UserID, &f.Name, &f.ContentType, &f.Size, &f.SHA256, &f.StorageKey, &f.CreatedAt, &f.CodeCount)
	if err != nil {
		return nil, mapErr(err)
	}
	return &f, nil
}

func (db *DB) queryFiles(ctx context.Context, query string, args ...any) ([]*File, error) {
	rows, err := db.Query(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []*File{}
	for rows.Next() {
		f, err := scanFile(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, f)
	}
	return out, rows.Err()
}

func (db *DB) CreateFile(ctx context.Context, f *File) error {
	if f.ID == "" {
		f.ID = NewID("file")
	}
	f.CreatedAt = Now()
	_, err := db.Exec(ctx, `INSERT INTO files (id, user_id, name, content_type, size, sha256, storage_key, created_at)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
		f.ID, f.UserID, f.Name, f.ContentType, f.Size, f.SHA256, f.StorageKey, f.CreatedAt)
	return mapErr(err)
}

// GetFile fetches a file by id. If userID is non-empty the file must belong to that user.
func (db *DB) GetFile(ctx context.Context, id, userID string) (*File, error) {
	if userID == "" {
		return scanFile(db.QueryRow(ctx, fileSelect+" WHERE f.id = ?", id))
	}
	return scanFile(db.QueryRow(ctx, fileSelect+" WHERE f.id = ? AND f.user_id = ?", id, userID))
}

func (db *DB) ListFiles(ctx context.Context, userID string) ([]*File, error) {
	return db.queryFiles(ctx, fileSelect+" WHERE f.user_id = ? ORDER BY f.created_at DESC, f.id", userID)
}

// DeleteFile removes a file row. Codes that served it stop resolving.
func (db *DB) DeleteFile(ctx context.Context, id string) error {
	res, err := db.Exec(ctx, "DELETE FROM files WHERE id = ?", id)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}

// FileUsageBytes returns the total size of a user's uploaded files.
func (db *DB) FileUsageBytes(ctx context.Context, userID string) (int64, error) {
	var n sql.NullInt64
	err := db.QueryRow(ctx, "SELECT SUM(size) FROM files WHERE user_id = ?", userID).Scan(&n)
	return n.Int64, err
}

// UnusedFilesBefore returns files created before cutoff that no code serves.
func (db *DB) UnusedFilesBefore(ctx context.Context, cutoff int64) ([]*File, error) {
	return db.queryFiles(ctx, fileSelect+` WHERE f.created_at < ?
		AND NOT EXISTS (SELECT 1 FROM qrcodes q WHERE q.file_id = f.id)`, cutoff)
}

// FileStorageKeys returns the storage key of every file row.
func (db *DB) FileStorageKeys(ctx context.Context) (map[string]bool, error) {
	rows, err := db.Query(ctx, "SELECT storage_key FROM files")
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	keys := map[string]bool{}
	for rows.Next() {
		var k string
		if err := rows.Scan(&k); err != nil {
			return nil, err
		}
		keys[k] = true
	}
	return keys, rows.Err()
}
