// Package files stores uploaded files on local disk for dynamic codes that
// serve a file instead of redirecting.
//
// Uploads are untrusted, so the store is strict: only a short list of
// document and image types is accepted, the extension and the sniffed
// content must agree, names on disk are random and never derived from user
// input, and every disk access goes through an os.Root confined to the
// upload directory.
package files

import (
	"bytes"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"net/http"
	"os"
	"path"
	"slices"
	"strings"
	"time"
	"unicode"
	"unicode/utf8"
)

// ErrTooLarge is returned when an upload exceeds the configured maximum.
var ErrTooLarge = errors.New("file is too large")

// TypeError explains why a file type was rejected.
type TypeError struct{ Message string }

func (e *TypeError) Error() string { return e.Message }

type fileType struct {
	contentType string
	sniffed     string // expected http.DetectContentType prefix
}

// types maps accepted extensions to the content type served to scanners.
// Formats a browser could render as a page (HTML, SVG, XML) are deliberately
// absent, and downloads are always served as attachments.
var types = map[string]fileType{
	".pdf":  {"application/pdf", "application/pdf"},
	".png":  {"image/png", "image/png"},
	".jpg":  {"image/jpeg", "image/jpeg"},
	".jpeg": {"image/jpeg", "image/jpeg"},
	".gif":  {"image/gif", "image/gif"},
	".webp": {"image/webp", "image/webp"},
	".txt":  {"text/plain; charset=utf-8", "text/plain"},
	".csv":  {"text/csv; charset=utf-8", "text/plain"},
	".docx": {"application/vnd.openxmlformats-officedocument.wordprocessingml.document", "application/zip"},
	".xlsx": {"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "application/zip"},
	".pptx": {"application/vnd.openxmlformats-officedocument.presentationml.presentation", "application/zip"},
}

// Extensions returns the accepted file extensions, sorted.
func Extensions() []string { return slices.Sorted(maps.Keys(types)) }

// Saved describes a file written by Store.Save.
type Saved struct {
	Name        string
	ContentType string
	Size        int64
	SHA256      string
	Key         string
}

// Store keeps uploads in a single directory.
type Store struct {
	root     *os.Root
	maxBytes int64
}

// Open creates dir if needed and returns a store confined to it.
func Open(dir string, maxBytes int64) (*Store, error) {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, fmt.Errorf("create upload directory: %w", err)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, fmt.Errorf("open upload directory: %w", err)
	}
	return &Store{root: root, maxBytes: maxBytes}, nil
}

// Close releases the directory handle.
func (s *Store) Close() error { return s.root.Close() }

// CleanName reduces a client-supplied file name to a safe display name:
// no directories, no control or format characters, at most 200 characters.
func CleanName(name string) string {
	name = strings.ReplaceAll(name, "\\", "/")
	name = path.Base(name)
	var b strings.Builder
	for _, r := range name {
		if r == utf8.RuneError || unicode.IsControl(r) || unicode.Is(unicode.Cf, r) || r == '"' {
			continue
		}
		b.WriteRune(r)
	}
	name = strings.TrimSpace(b.String())
	if strings.Trim(name, "./") == "" {
		name = ""
	}
	if utf8.RuneCountInString(name) > 200 {
		ext := path.Ext(name)
		if utf8.RuneCountInString(ext) > 10 {
			ext = ""
		}
		runes := []rune(strings.TrimSuffix(name, ext))
		name = string(runes[:200-utf8.RuneCountInString(ext)]) + ext
	}
	return name
}

func newKey() string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		panic("crypto/rand failed: " + err.Error())
	}
	return hex.EncodeToString(b)
}

// validKey reports whether key looks like one generated by newKey.
func validKey(key string) bool {
	if len(key) != 32 {
		return false
	}
	_, err := hex.DecodeString(key)
	return err == nil && strings.ToLower(key) == key
}

// Save validates and stores the contents of r under a new random key.
func (s *Store) Save(r io.Reader, name string) (*Saved, error) {
	name = CleanName(name)
	ext := strings.ToLower(path.Ext(name))
	ft, ok := types[ext]
	if !ok {
		return nil, &TypeError{"type is not allowed (accepted: " + strings.Join(Extensions(), ", ") + ")"}
	}

	key := newKey()
	tmp := ".upload-" + key
	f, err := s.root.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return nil, err
	}
	keep := false
	defer func() {
		if !keep {
			f.Close()
			_ = s.root.Remove(tmp)
		}
	}()

	head := make([]byte, 512)
	n, err := io.ReadFull(r, head)
	if err != nil && !errors.Is(err, io.ErrUnexpectedEOF) && !errors.Is(err, io.EOF) {
		return nil, err
	}
	head = head[:n]
	if n == 0 {
		return nil, &TypeError{"is empty"}
	}
	if !strings.HasPrefix(http.DetectContentType(head), ft.sniffed) {
		return nil, &TypeError{"contents do not match the " + ext + " extension"}
	}

	h := sha256.New()
	limited := io.LimitReader(io.MultiReader(bytes.NewReader(head), r), s.maxBytes+1)
	size, err := io.Copy(io.MultiWriter(f, h), limited)
	if err != nil {
		return nil, err
	}
	if size > s.maxBytes {
		return nil, ErrTooLarge
	}
	if err := f.Sync(); err != nil {
		return nil, err
	}
	if err := f.Close(); err != nil {
		return nil, err
	}
	if err := s.root.Rename(tmp, key); err != nil {
		return nil, err
	}
	keep = true
	return &Saved{Name: name, ContentType: ft.contentType, Size: size, SHA256: hex.EncodeToString(h.Sum(nil)), Key: key}, nil
}

// Open returns the stored file for key.
func (s *Store) Open(key string) (*os.File, error) {
	if !validKey(key) {
		return nil, fs.ErrNotExist
	}
	return s.root.Open(key)
}

// Remove deletes the stored file for key. A missing file is not an error.
func (s *Store) Remove(key string) error {
	if !validKey(key) {
		return nil
	}
	if err := s.root.Remove(key); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// Sweep deletes files older than minAge that are not in known, including
// leftovers from interrupted uploads. It returns the number removed.
func (s *Store) Sweep(known map[string]bool, minAge time.Duration) (int, error) {
	dir, err := s.root.Open(".")
	if err != nil {
		return 0, err
	}
	entries, err := dir.ReadDir(-1)
	dir.Close()
	if err != nil {
		return 0, err
	}
	cutoff := time.Now().Add(-minAge)
	removed := 0
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || known[name] {
			continue
		}
		if !validKey(name) && !strings.HasPrefix(name, ".upload-") {
			continue
		}
		info, err := e.Info()
		if err != nil || info.ModTime().After(cutoff) {
			continue
		}
		if err := s.root.Remove(name); err == nil {
			removed++
		}
	}
	return removed, nil
}
